/**
 * Translate a key into the given language with parameter interpolation.
 * Falls back to English if the translation is missing.
 */
export function t(
  key: string,
  lang: string = 'en',
  params?: Record<string, string | number>,
): string {
  const language = (lang in DEFAULT_TRANSLATIONS ? lang : 'en') as SupportedLanguage;
  let text = DEFAULT_TRANSLATIONS[language]?.[key] || DEFAULT_TRANSLATIONS.en[key] || key;

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replaceAll(`{${k}}`, String(v));
    });
  }

  return text;
}
